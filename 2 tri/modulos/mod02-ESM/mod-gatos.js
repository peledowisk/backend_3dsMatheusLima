

export function banhoGato(racaGato, tipoBanho)
{
    return 'Gato ${racaGato} fez um banho tipo: ${tipoBanho}'
}


export function tosaGato(racaGato, tipoTosa)
{
return 'Gato ${racaGato} fez uma tosa do tipo: ${tipoTosa}'
}

export function alimentarGato(racaGato, tipoRacao)
{
    return 'Gato ${racaGato} foi alimentado com: ${tipoRacao}'
}